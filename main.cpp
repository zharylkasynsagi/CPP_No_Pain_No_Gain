// МОДУЛЬ 1: Учет рабочего времени и блокировка
void moduleWorkTimeValidation() {
    cout << "\n========================================\n";
    cout << "   МОДУЛЬ 1: УЧЕТ РАБОЧЕГО ВРЕМЕНИ\n";
    cout << "========================================\n";

    int days = 0;
    double rate = 0.0;
    int hoursPerDay = 0;

    cout << "Введите количество рабочих дней в неделе (ожидается 5): ";
    while (!(cin >> days)) {
        cout << "Ошибка ввода! Введите число: ";
        clearInput();
    }

    cout << "Введите ставку (ожидается 0.5): ";
    while (!(cin >> rate)) {
        cout << "Ошибка ввода! Введите число: ";
        clearInput();
    }

    // Цикл блокировки
    do {
        cout << "Введите количество рабочих часов в день: ";
        while (!(cin >> hoursPerDay)) {
            cout << "Ошибка ввода! Введите число: ";
            clearInput();
        }

        if (hoursPerDay == 2) {
            cout << "\n---------------------------------------------------\n";
            cout << "Ошибка! При 5-дневной рабочей неделе 2 часа в день\n";
            cout << "составляют 10 часов в неделю. Дефицит рабочего времени:\n";
            cout << "10 часов (50% от нормы 0.5 ставки). Налицо факт\n";
            cout << "предоставления заведомо ложных сведений работодателю.\n";
            cout << "---------------------------------------------------\n";
            cout << "ДОСТУП ЗАБЛОКИРОВАН! Введите корректную норму (4 часа в день).\n\n";
        } else if (hoursPerDay != 4) {
            cout << "Некорректная норма для 0.5 ставки. Подтвердите норму в 4 часа в день.\n\n";
        }
    } while (hoursPerDay != 4);

    cout << "\n[ОК] Норма в 4 часа в день (20 часов/неделю) подтверждена.\n";
}
