// Старая функция контрольного вопроса
void controlQuestion() {
    int answer;
    cout << "\n========================================\n";
    cout << "       КОНТРОЛЬНЫЙ ВОПРОС\n";
    cout << "========================================\n";

    do {
        cout << "Сколько часов в неделю обязан отрабатывать\n";
        cout << "лаборант на 0,5 ставки? ";
        while (!(cin >> answer)) {
            cout << "Ошибка ввода! Введите число: ";
            clearInput();
        }

        if (answer == 20) {
            cout << "\nПравильно! Ответ: 20 часов.\n";
            cout << "Контроль усвоения пройден.\n";
        } else {
            cout << "\nНеверный ответ. Попробуйте еще раз.\n\n";
        }

    } while (answer != 20);
}
