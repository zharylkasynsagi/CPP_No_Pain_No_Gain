// ============================================================
// Безопасный ввод чисел
// ============================================================
template <typename T>
T inputNumber(const string& message) {
    T value;
    string line;

    while (true) {
        cout << message;
        getline(cin, line);

        stringstream ss(line);
        char extra;

        if (ss >> value && !(ss >> extra)) {
            return value;
        }

        cout << "Ошибка! Введите корректное число.\n";
    }
}

// ============================================================
// Модуль 1: учет рабочего времени
// ============================================================
void workingTimeModule() {
    cout << "\n========== УЧЕТ РАБОЧЕГО ВРЕМЕНИ ==========\n";

    const int requiredDays = 5;
    const double requiredRate = 0.5;
    const double fullTimeHours = 40.0;

    int days;
    double rate;

    // Проверка количества рабочих дней
    do {
        days = inputNumber<int>(
            "Введите количество рабочих дней в неделю: ");

        if (days != requiredDays) {
            cout << "Ошибка! Для данного задания необходимо ввести "
                 << requiredDays << " рабочих дней.\n";
        }

    } while (days != requiredDays);

    // Проверка ставки
    do {
        rate = inputNumber<double>(
            "Введите ставку (например, 0.5): ");

        if (rate != requiredRate) {
            cout << "Ошибка! Для данного задания необходимо ввести "
                 << requiredRate << " ставки.\n";
        }

    } while (rate != requiredRate);

    // Расчет нормы
    double weeklyNorm = fullTimeHours * rate;
    double dailyNorm = weeklyNorm / requiredDays;

    cout << fixed << setprecision(1);

    cout << "\nНорма рабочего времени:\n";
    cout << "Рабочих дней в неделю: " << requiredDays << "\n";
    cout << "Ставка: " << rate << "\n";
    cout << "Норма часов в неделю: " << weeklyNorm << "\n";
    cout << "Норма часов в день: " << dailyNorm << "\n";

    // Проверка фактического количества часов
    double actualHours;

    do {
        actualHours = inputNumber<double>(
            "\nСколько часов в день вы планируете работать? ");

        if (actualHours <= 0 || actualHours > 24) {
            cout << "Введите значение больше 0 и не более 24.\n";
            continue;
        }

        double actualWeekly = actualHours * requiredDays;

        // Если введено меньше нормы
        if (actualWeekly < weeklyNorm) {

            double deficit = weeklyNorm - actualWeekly;
            double percentOfNorm =
                (deficit / weeklyNorm) * 100.0;

            cout << "\nОШИБКА!\n";
            cout << "При 5-дневной рабочей неделе "
                 << actualHours
                 << " часа в день составляют "
                 << actualWeekly
                 << " часов в неделю.\n";

            cout << "Дефицит рабочего времени: "
                 << deficit << " часов ("
                 << percentOfNorm
                 << "% от нормы 0.5 ставки).\n";

            cout << "Налицо факт предоставления заведомо "
                    "ложных сведений работодателю.\n";

            cout << "\nРабота модуля заблокирована.\n";
            cout << "Необходимо ввести правильную норму: "
                 << dailyNorm
                 << " часа в день.\n";

        } else if (actualWeekly > weeklyNorm) {

            cout << "\nВнимание! Введенное время превышает "
                    "расчетную норму.\n";

        } else {

            cout << "\nРабочее время соответствует норме.\n";
        }

        // Повторяем ввод, пока не будет введено ровно 4 часа
        if (actualHours != dailyNorm) {
            cout << "\nВведите правильное значение "
                    "для продолжения.\n";
        }

    } while (actualHours != dailyNorm);

    cout << "\nНорма подтверждена: "
         << dailyNorm
         << " часа в день.\n";

    cout << "Модуль учета рабочего времени завершен.\n";
}

